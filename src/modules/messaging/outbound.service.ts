import { and, eq, sql } from 'drizzle-orm'
import type { Database } from '../../db/client.ts'
import { channelAccounts, contacts, conversations, messageTemplates, messages } from '../../db/schema/index.ts'
import { type MemberScope, withMember } from '../access/member-scope.ts'
import type { ChannelCredentials } from '../channels/channel-credentials.ts'
import { ConversationNotFoundError } from '../conversations/conversation-commands.ts'
import type { ConversationQueries } from '../conversations/conversation-queries.ts'
import { renderBody } from '../templates/template-body.ts'
import { withTenant } from '../tenancy/tenant-scope.ts'
import { WhatsAppApiError, type WhatsAppSender } from '../whatsapp/cloud-api.client.ts'
import { isWithinServiceWindow } from './service-window.ts'

export class ServiceWindowClosedError extends Error {
  constructor() {
    super('The 24 h service window is closed: only an approved template can be sent')
    this.name = 'ServiceWindowClosedError'
  }
}

export class TemplateNotUsableError extends Error {
  constructor(reason: string) {
    super(`Template cannot be sent: ${reason}`)
    this.name = 'TemplateNotUsableError'
  }
}

interface Origin {
  tenantId: string
  userId: string
  conversationId: string
  /** Generated by the panel per message: the same id never sends twice. */
  clientMessageId: string
}

export interface SendTextCommand extends Origin {
  body: string
}

export interface SendTemplateCommand extends Origin {
  templateId: string
  /** Values for {{1}}, {{2}}... in order. */
  parameters: string[]
}

export type SendOutcome = 'sent' | 'failed' | 'already_sent'

export interface SendResult {
  messageId: number
  outcome: SendOutcome
}

/** Where the message goes: the conversation's number and customer. */
interface Target {
  channelAccountId: string
  phoneNumberId: string
  wabaId: string
  to: string
  lastInboundAt: Date | null
}

/** What to store and how to hand it to Meta, decided inside the company transaction. */
interface Draft {
  row: Pick<typeof messages.$inferInsert, 'type' | 'body' | 'templateId'>
  deliver: (target: Target, accessToken: string) => Promise<{ waMessageId: string }>
}

const MAX_ERROR_LENGTH = 300

/**
 * Replies from the panel, at most once (pattern reused from project-1, now per company):
 *   1. In the caller's company transaction: visibility, the draft (text: 24 h window;
 *      template: approved and of this number's account), store it (idempotent by
 *      client_message_id), bump the conversation. Commit.
 *   2. Outside any transaction: decrypt the number's token and call Meta.
 *   3. In a new company transaction: record the Meta id or the error, once.
 * Nothing retries automatically: an unknown outcome stays visible instead of risking
 * a duplicate message to the customer.
 */
export class OutboundService {
  constructor(
    private readonly db: Database,
    private readonly queries: ConversationQueries,
    private readonly credentials: ChannelCredentials,
    private readonly sender: WhatsAppSender,
    private readonly now: () => Date = () => new Date(),
  ) {}

  sendText(command: SendTextCommand): Promise<SendResult> {
    return this.dispatch(command, (_scope, target) => {
      if (!isWithinServiceWindow(target.lastInboundAt, this.now())) throw new ServiceWindowClosedError()
      return Promise.resolve({
        row: { type: 'text', body: command.body, templateId: null },
        deliver: (to, accessToken) => this.sender.sendText({ phoneNumberId: to.phoneNumberId, accessToken, to: to.to, body: command.body }),
      })
    })
  }

  /** Templates are what may be sent outside the 24 h window. */
  sendTemplate(command: SendTemplateCommand): Promise<SendResult> {
    return this.dispatch(command, async (scope, target) => {
      const [template] = await scope.tx
        .select({ name: messageTemplates.name, language: messageTemplates.language, status: messageTemplates.status, wabaId: messageTemplates.wabaId, body: messageTemplates.body })
        .from(messageTemplates)
        .where(and(eq(messageTemplates.tenantId, scope.tenantId), eq(messageTemplates.id, command.templateId)))
      if (!template) throw new TemplateNotUsableError('not found')
      if (template.status !== 'approved') throw new TemplateNotUsableError('not approved by Meta')
      if (template.wabaId !== target.wabaId) throw new TemplateNotUsableError('belongs to another WhatsApp Business Account')
      const body = renderBody(template.body, command.parameters)
      return {
        row: { type: 'template', body, templateId: command.templateId },
        deliver: (to, accessToken) =>
          this.sender.sendTemplate({
            phoneNumberId: to.phoneNumberId,
            accessToken,
            to: to.to,
            name: template.name,
            language: template.language,
            bodyParameters: command.parameters,
          }),
      }
    })
  }

  private async dispatch(origin: Origin, draftFor: (scope: MemberScope, target: Target) => Promise<Draft>): Promise<SendResult> {
    const prepared = await withMember(this.db, origin.tenantId, origin.userId, (scope) => this.prepare(scope, origin, draftFor))
    if (!prepared.isNew) return { messageId: prepared.messageId, outcome: 'already_sent' }

    let result: { waMessageId: string } | { error: string }
    try {
      const accessToken = await this.credentials.accessTokenFor(origin.tenantId, prepared.target.channelAccountId)
      result = accessToken ? await prepared.deliver(prepared.target, accessToken) : { error: 'no_credentials' }
    } catch (error) {
      result = { error: describe(error) }
    }

    await withTenant(this.db, origin.tenantId, ({ tx, tenantId }) =>
      tx
        .update(messages)
        .set('waMessageId' in result ? { waMessageId: result.waMessageId } : { sendError: result.error })
        .where(and(eq(messages.tenantId, tenantId), eq(messages.id, prepared.messageId))),
    )
    return { messageId: prepared.messageId, outcome: 'waMessageId' in result ? 'sent' : 'failed' }
  }

  private async prepare(scope: MemberScope, origin: Origin, draftFor: (scope: MemberScope, target: Target) => Promise<Draft>) {
    const { tx, tenantId, member } = scope
    // Same visibility as reading it: what you cannot see, you cannot answer.
    if (!(await this.queries.get(scope, origin.conversationId))) throw new ConversationNotFoundError()

    // A retry of a request already handled answers with the first one and sends nothing,
    // even if the window has closed or the template changed since.
    const [existing] = await tx
      .select({ id: messages.id, conversationId: messages.conversationId })
      .from(messages)
      .where(and(eq(messages.tenantId, tenantId), eq(messages.clientMessageId, origin.clientMessageId)))
    if (existing) {
      if (existing.conversationId !== origin.conversationId) throw new ConversationNotFoundError()
      return { messageId: existing.id, isNew: false as const }
    }

    const [target] = await tx
      .select({
        channelAccountId: contacts.channelAccountId,
        phoneNumberId: channelAccounts.phoneNumberId,
        wabaId: channelAccounts.wabaId,
        to: contacts.waId,
        lastInboundAt: contacts.lastInboundAt,
      })
      .from(conversations)
      .innerJoin(contacts, and(eq(contacts.tenantId, conversations.tenantId), eq(contacts.id, conversations.contactId)))
      .innerJoin(channelAccounts, and(eq(channelAccounts.tenantId, contacts.tenantId), eq(channelAccounts.id, contacts.channelAccountId)))
      .where(and(eq(conversations.tenantId, tenantId), eq(conversations.id, origin.conversationId)))
    if (!target) throw new ConversationNotFoundError()

    const draft = await draftFor(scope, target)
    // ON CONFLICT covers two identical requests racing past the lookup above.
    const [stored] = await tx
      .insert(messages)
      .values({
        tenantId,
        conversationId: origin.conversationId,
        clientMessageId: origin.clientMessageId,
        direction: 'out',
        author: 'staff',
        authorUserId: member.userId,
        ...draft.row,
      })
      .onConflictDoNothing({ target: [messages.tenantId, messages.clientMessageId] })
      .returning({ id: messages.id })
    if (!stored) throw new ConcurrentSendError()

    await tx
      .update(conversations)
      .set({ lastActivityAt: sql`now()` })
      .where(and(eq(conversations.tenantId, tenantId), eq(conversations.id, origin.conversationId)))
    return { messageId: stored.id, isNew: true as const, target, deliver: draft.deliver }
  }
}

/** The same clientMessageId arrived twice at the same instant; the other request sends it. */
export class ConcurrentSendError extends Error {
  constructor() {
    super('The same message is being sent by another request')
    this.name = 'ConcurrentSendError'
  }
}

/** What gets stored about a failed send: Meta's code and message, never the request. */
function describe(error: unknown): string {
  const text = error instanceof WhatsAppApiError ? `meta_${error.metaCode ?? error.httpStatus ?? 'network'}: ${error.message}` : 'unexpected_error'
  return text.slice(0, MAX_ERROR_LENGTH)
}
